import { Buffer } from "node:buffer";
import { spawnSync } from "node:child_process";
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { basename, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "..", "..");
const snapshotPath = resolve(packageRoot, "openapi/hbpos.openapi.json");
const generatedPath = resolve(packageRoot, "src/generated/hbpos/schema.d.ts");
const checkMode = process.argv.slice(2).includes("--check");

if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("只支持 --check；默认命令会刷新由测试宿主导出的共享快照和 DTO。");
}

const temporaryDirectory = mkdtempSync(resolve(tmpdir(), "hbpos-openapi-"));
const exportedSnapshotPath = resolve(temporaryDirectory, "hbpos.openapi.json");
const temporaryGeneratedPath = resolve(temporaryDirectory, "schema.d.ts");

try {
  run(
    "dotnet",
    [
      "test",
      "apps/pos-wpf/tests/Hbpos.Api.Tests/Hbpos.Api.Tests.csproj",
      "--filter",
      "FullyQualifiedName~OpenApiSnapshotExportTests",
      "--no-restore",
    ],
    { HBPOS_OPENAPI_SNAPSHOT_OUTPUT: exportedSnapshotPath },
  );

  const exportedSnapshot = readFileSync(exportedSnapshotPath);
  if (exportedSnapshot.length === 0) {
    throw new Error("Hbpos.Api 测试宿主未导出 OpenAPI 文档。");
  }

  const openapiPackage = require.resolve("openapi-typescript/package.json");
  run(process.execPath, [
    resolve(dirname(openapiPackage), "bin", "cli.js"),
    exportedSnapshotPath,
    "-o",
    temporaryGeneratedPath,
  ]);
  const generated = Buffer.concat([
    Buffer.from(
      "// AUTO-GENERATED by packages/pos-api-client/scripts/generate-hbpos-client.mjs. DO NOT EDIT.\n\n",
    ),
    readFileSync(temporaryGeneratedPath),
  ]);

  if (checkMode) {
    assertSame(
      snapshotPath,
      exportedSnapshot,
      "共享 OpenAPI 快照已漂移；请显式运行 npm run generate:hbpos-client 后审查变更。",
    );
    assertSame(
      generatedPath,
      generated,
      "共享 Hbpos DTO 已漂移；请显式运行 npm run generate:hbpos-client 后审查变更。",
    );
    console.log("shared hbpos OpenAPI code generation drift check: ok");
  } else {
    mkdirSync(dirname(snapshotPath), { recursive: true });
    mkdirSync(dirname(generatedPath), { recursive: true });
    writeFileSync(snapshotPath, exportedSnapshot);
    writeFileSync(generatedPath, generated);
    console.log(
      `exported ${relative(repositoryRoot, snapshotPath)} and ${relative(repositoryRoot, generatedPath)}`,
    );
  }
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}

function run(command, argumentsList, extraEnvironment = {}) {
  const result = spawnSync(command, argumentsList, {
    cwd: repositoryRoot,
    env: { ...process.env, ...extraEnvironment },
    encoding: "utf8",
    stdio: "inherit",
  });
  if (result.status !== 0) {
    throw new Error(
      `${command} ${argumentsList.map((argument) => basename(argument)).join(" ")} failed.`,
    );
  }
}

function assertSame(path, expected, message) {
  let actual;
  try {
    actual = readFileSync(path);
  } catch {
    throw new Error(message);
  }
  if (!actual.equals(expected)) throw new Error(message);
}
