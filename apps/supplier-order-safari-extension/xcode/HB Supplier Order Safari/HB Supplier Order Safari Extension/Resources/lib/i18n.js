export function normalizeLocale(locale) {
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function resolveInitialLocale(storedLocale, preferredLanguages = []) {
  // 手动选择优先；只有首次没有合法保存值时，才根据系统首选语言决定。
  if (SUPPORTED_LOCALES.includes(storedLocale)) {
    return storedLocale;
  }

  const languages = Array.isArray(preferredLanguages)
    ? preferredLanguages
    : [preferredLanguages];
  const systemLocale = languages.find(
    (language) => typeof language === 'string' && language.trim(),
  );

  return /^zh(?:-|$)/i.test(systemLocale?.trim() || '') ? 'zh' : 'en';
}

export function t(locale, key) {
  const dict = MESSAGES[locale] || MESSAGES[DEFAULT_LOCALE];
  return dict[key] != null ? dict[key] : key;
}
